const fs   = require("fs");
const path = require("path");
const os   = require("os");
const { loadConfig } = require("./config");
const { obfuscate } = require("./obfuscate");
const { computeHash, signFile, generateRuntimeGuard } = require("./signer");

// ─── esbuild loader ──────────────────────────────────────────────────────────
// When running inside a pkg bundle (standalone .exe) the native esbuild binary
// is not available. We fall back to esbuild-wasm which is pure JavaScript.
// Outside pkg we use the normal native esbuild for maximum speed.

var _esbuildInstance = null;

async function getEsbuild() {
  if (_esbuildInstance) return _esbuildInstance;

  if (process.pkg) {
    // Inside a pkg .exe the snapshot paths are virtual — an external node.js process
    // spawned by esbuild-wasm can't access them. We extract 3 files to a real tmpdir
    // then patch child_process.spawn to redirect the service script to the real path.
    //
    // lib/esbuild-vendor.js is generated by scripts/build-releases.js just before
    // pkg compilation. It exports the two service scripts as string constants.
    // V8 bytecode preserves string literal values — require() returns them correctly.
    const esbuildWasm = require("esbuild-wasm");
    const vendor      = require("./esbuild-vendor");

    const tmpDir = path.join(os.tmpdir(), "kra-secure-esbuild-" + process.version);
    const tmpBin = path.join(tmpDir, "bin");

    if (!fs.existsSync(path.join(tmpBin, "esbuild"))) {
      fs.mkdirSync(tmpBin, { recursive: true });
      fs.writeFileSync(path.join(tmpBin, "esbuild"),           vendor.serviceCode,  "utf8");
      fs.writeFileSync(path.join(tmpDir, "wasm_exec_node.js"), vendor.wasmExecCode, "utf8");
      fs.writeFileSync(path.join(tmpDir, "wasm_exec.js"),      vendor.wasmExecShim, "utf8");
      // wasmBase64 avoids pkg's binary-asset corruption (non-UTF-8 bytes → U+FFFD)
      fs.writeFileSync(path.join(tmpDir, "esbuild.wasm"),
        Buffer.from(vendor.wasmBase64, "base64"));
    }

    // esbuild-wasm's ensureServiceIsRunning() spawns:
    //   child_process.spawn("node", ["/snapshot/.../bin/esbuild", "--service=..."])
    // Redirect args[0] to the extracted real file.
    const cp = require("child_process");
    const _origSpawn = cp.spawn;
    cp.spawn = function(cmd, args, opts) {
      if (Array.isArray(args) && typeof args[0] === "string" && args[0].includes("esbuild-wasm")) {
        args = [path.join(tmpBin, "esbuild")].concat(args.slice(1));
      }
      return _origSpawn.call(this, cmd, args, opts);
    };

    await esbuildWasm.initialize({});
    _esbuildInstance = esbuildWasm;
  } else {
    _esbuildInstance = require("esbuild");
  }

  return _esbuildInstance;
}

// Build a single entry point.
async function buildOne(config) {
  const inputFile = path.resolve(process.cwd(), config.input);
  const outputFile = path.resolve(process.cwd(), config.output);
  const mode = config.mode || "production";

  if (mode !== "production" && mode !== "debug") {
    throw new Error(
      'Mode invalide: "' + mode + '". Valeurs acceptées: production, debug.'
    );
  }

  if (!fs.existsSync(inputFile)) {
    throw new Error("Fichier d'entrée introuvable: " + inputFile);
  }

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });

  const esbuild = await getEsbuild();

  // Debug mode: bundle only, source maps, no obfuscation
  if (mode === "debug") {
    await esbuild.build({
      entryPoints: [inputFile],
      bundle: true,
      minify: false,
      outfile: outputFile,
      platform: "browser",
      sourcemap: !process.pkg, // source maps not useful inside an .exe
      define: { "process.env.NODE_ENV": '"development"' }
    });
    const stats = fs.statSync(outputFile);
    return { output: outputFile, mode: "debug", obfuscated: false, size: stats.size };
  }

  // Production: bundle → obfuscate → optionally sign
  const tmpFile = outputFile + ".__kra_tmp__";
  try {
    await esbuild.build({
      entryPoints: [inputFile],
      bundle: true,
      minify: false,
      outfile: tmpFile,
      platform: "browser",
      define: { "process.env.NODE_ENV": '"production"' }
    });

    const bundled = fs.readFileSync(tmpFile, "utf8");
    const obfuscated = obfuscate(bundled, config.options || {});

    var finalCode = obfuscated;
    var sigInfo = null;
    const at = config.antiTampering || {};

    if (at.signature) {
      const algorithm = at.algorithm || "sha256";
      const hash = computeHash(obfuscated, algorithm);
      const guard = generateRuntimeGuard(hash, at);
      finalCode = guard + "\n" + obfuscated;
    }

    fs.writeFileSync(outputFile, finalCode, "utf8");

    if (at.enabled || at.signature) {
      try {
        sigInfo = signFile(outputFile, { algorithm: at.algorithm || "sha256" });
      } catch (_) {
        // Non-fatal: signing failed, build still succeeds
      }
    }

    const stats = fs.statSync(outputFile);
    return {
      output: outputFile,
      mode: "production",
      obfuscated: true,
      size: stats.size,
      signature: sigInfo
    };
  } finally {
    if (fs.existsSync(tmpFile)) {
      try { fs.unlinkSync(tmpFile); } catch (_) {}
    }
  }
}

// Resolve the [name] placeholder in output paths (for multi-file builds).
function resolveOutputPath(outputPattern, inputFile) {
  const name = path.basename(inputFile, path.extname(inputFile));
  return outputPattern.replace(/\[name\]/g, name);
}

// Main build function — accepts a pre-loaded config or a plain options object.
async function build(configOrOptions) {
  configOrOptions = configOrOptions || {};

  // If not pre-loaded, merge with any config file on disk
  var config;
  if (configOrOptions._isLoaded) {
    config = configOrOptions;
  } else {
    const fileConfig = loadConfig(configOrOptions.configPath);
    config = Object.assign(fileConfig, configOrOptions, { _isLoaded: true });
  }

  // Multi-file input (array of entry points)
  if (Array.isArray(config.input)) {
    const results = [];
    for (const inputFile of config.input) {
      const resolvedOutput = resolveOutputPath(config.output, inputFile);
      const single = Object.assign({}, config, {
        input: inputFile,
        output: resolvedOutput,
        _isLoaded: true
      });
      results.push(await buildOne(single));
    }
    return results;
  }

  return buildOne(config);
}

module.exports = { build };
